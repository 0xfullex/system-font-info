// Generates src/sfnt/language_tables.cpp: Windows LCID and Macintosh language
// code -> BCP 47 mappings used to label `name` table records.
//
// macOS only (uses the system ICU and CoreFoundation):
//   clang -O2 scripts/gen-language-tables.c -licucore -framework CoreFoundation -o /tmp/gen
//   /tmp/gen > src/sfnt/language_tables.cpp
#include <CoreFoundation/CoreFoundation.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

// The SDK does not ship ICU headers; declare the two stable C APIs we need.
typedef int32_t UErrorCode;
typedef int8_t UBool;
int32_t uloc_getLocaleForLCID(uint32_t hostID, char *locale, int32_t capacity, UErrorCode *status);
int32_t uloc_toLanguageTag(const char *localeID, char *langtag, int32_t capacity, UBool strict, UErrorCode *status);
uint32_t uloc_getLCID(const char *localeID);

// Windows LocaleNameToLCID / LCIDToLocaleName omit the script for Chinese
// regional locales; match that so tags agree with what DirectWrite reports.
static void windowsStyle(uint32_t lcid, char *tag) {
  struct { uint32_t lcid; const char *tag; } fixes[] = {
      {0x0004, "zh-Hans"}, {0x7C04, "zh-Hant"}, {0x0804, "zh-CN"}, {0x0404, "zh-TW"},
      {0x0C04, "zh-HK"},   {0x1004, "zh-SG"},   {0x1404, "zh-MO"},
  };
  for (size_t i = 0; i < sizeof fixes / sizeof fixes[0]; i++)
    if (fixes[i].lcid == lcid) strcpy(tag, fixes[i].tag);
}

static int toTag(const char *icu, char *out, int cap) {
  UErrorCode st = 0;
  uloc_toLanguageTag(icu, out, cap, 1, &st);
  return st <= 0 && out[0] && strcmp(out, "und") != 0;
}

int main(void) {
  printf("// Generated by scripts/gen-language-tables.c. Do not edit by hand.\n");
  printf("// Source: ICU uloc_getLocaleForLCID and CoreFoundation script-manager codes (macOS).\n");
  printf("#include \"language_tables.h\"\n\nnamespace sfi::sfnt {\n\n");
  // One entry per line keeps a regenerated table easy to diff; the markers stop
  // clang-format from packing the entries into columns.
  printf("// clang-format off\nconst LcidEntry kLcidTable[] = {\n");
  int lcids = 0;
  for (uint32_t lcid = 1; lcid <= 0xFFFF; lcid++) {
    char icu[128] = {0}, tag[128] = {0};
    UErrorCode st = 0;
    uloc_getLocaleForLCID(lcid, icu, sizeof icu, &st);
    if (st != 0 || !icu[0]) continue;
    // ICU silently falls back to the primary language for unknown sublanguages;
    // keep only mappings that round-trip to the same LCID.
    if (uloc_getLCID(icu) != lcid) continue;
    if (!toTag(icu, tag, sizeof tag)) continue;
    windowsStyle(lcid, tag);
    printf("    {0x%04X, \"%s\"},\n", lcid, tag);
    lcids++;
  }
  printf("};\n// clang-format on\nconst size_t kLcidTableSize = %d;\n\n", lcids);

  printf("// clang-format off\nconst MacLanguageEntry kMacLanguageTable[] = {\n");
  int macs = 0;
  for (int code = 0; code <= 150; code++) {
    CFStringRef id = CFLocaleCreateCanonicalLocaleIdentifierFromScriptManagerCodes(NULL, (LangCode)code, -1);
    if (!id) continue;
    char icu[128] = {0}, tag[128] = {0};
    CFStringGetCString(id, icu, sizeof icu, kCFStringEncodingUTF8);
    CFRelease(id);
    if (!icu[0] || !toTag(icu, tag, sizeof tag)) continue;
    printf("    {%d, \"%s\"},\n", code, tag);
    macs++;
  }
  printf("};\n// clang-format on\nconst size_t kMacLanguageTableSize = %d;\n\n}  // namespace sfi::sfnt\n", macs);
  return 0;
}
